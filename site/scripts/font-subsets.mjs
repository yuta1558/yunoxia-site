// Writes src/styles/fonts.generated.css: the Zen Kaku Gothic New @font-face rules the site actually needs.
// Fontsource ships ~120 unicode-range subsets per weight; importing three weights whole puts ~370 rules
// (≈180 KB gzipped) of render-blocking CSS in front of the first paint. Browsers only download the
// subsets a page uses anyway, so dropping the rules for characters the site never shows costs nothing.
// Characters come from the source and content files; weight 700 is used only by the top h1.
// Runs before every build (package.json "build"); a character missing here falls back to the system gothic.
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const PKG = 'node_modules/@fontsource/zen-kaku-gothic-new';
const OUT = 'src/styles/fonts.generated.css';
const TOP_H1 = '分解して、理解して、作り替える。';

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

const used = new Set();
for (const file of walk('src').filter((f) => /\.(astro|md|mdx|ts|json)$/.test(f) && !f.endsWith('.generated.css'))) {
  for (const ch of readFileSync(file, 'utf8')) used.add(ch.codePointAt(0));
}

// Parse "U+3000-303F, U+30A0" into [lo, hi] pairs
const ranges = (spec) =>
  spec.split(',').map((r) => {
    const [lo, hi] = r.trim().replace(/^U\+/i, '').split('-');
    return [parseInt(lo, 16), parseInt(hi ?? lo, 16)];
  });
const hits = (spec, chars) => ranges(spec).some(([lo, hi]) => [...chars].some((c) => c >= lo && c <= hi));

const keep = (weight, chars) => {
  const css = readFileSync(`${PKG}/${weight}.css`, 'utf8');
  const faces = css.match(/@font-face\s*\{[^}]*\}/g) ?? [];
  return faces
    .filter((f) => hits(/unicode-range:\s*([^;]+);/.exec(f)[1], chars))
    .map((f) => f.replace(/url\(\.\/files\//g, `url(../../${PKG}/files/`));
};

// Weight 500 is used only by inline strong in prose: keep rules for characters that appear inside
// strong markup in the source (**…**, __…__, <strong>, <b>). Normally none. CMS posts load the full set below.
const strong = new Set();
const STRONG = /\*\*([^*\n]+)\*\*|__([^_\n]+)__|<(strong|b)\b[^>]*>([\s\S]*?)<\/\3>/g;
for (const file of walk('src').filter((f) => /\.(astro|md|mdx)$/.test(f))) {
  for (const m of readFileSync(file, 'utf8').matchAll(STRONG)) {
    for (const ch of m[1] ?? m[2] ?? m[4]) strong.add(ch.codePointAt(0));
  }
}

const h1 = new Set([...TOP_H1].map((c) => c.codePointAt(0)));
const out = [
  '/* Generated by scripts/font-subsets.mjs — do not edit. */',
  ...keep(300, used),
  ...keep(400, used),
  ...(strong.size ? keep(500, strong) : []),
  ...keep(700, h1),
].join('\n');
writeFileSync(OUT, out + '\n');
console.log(`${OUT}: ${out.match(/@font-face/g).length} @font-face rules`);

// Full-coverage stylesheet (300, 400, 500) for CMS post pages, whose characters the build never sees.
// It leaves out the faces the subset above already declares, so a post never fetches a slice twice.
// /assets/* is immutable, so the directory is named by a hash of the stylesheet: a new subset or a new
// package version gives a new path. src/pages/log/index.astro reads it from fonts.generated.json.
const inSubset = new Set(
  (out.match(/@font-face\s*\{[^}]*\}/g) ?? []).map((f) => `${/font-weight:\s*(\d+)/.exec(f)[1]}|${/unicode-range:\s*([^;]+);/.exec(f)[1]}`),
);
const copied = new Set();
const full = [300, 400, 500].flatMap((w) =>
  (readFileSync(`${PKG}/${w}.css`, 'utf8').match(/@font-face\s*\{[^}]*\}/g) ?? [])
    .filter((face) => !inSubset.has(`${w}|${/unicode-range:\s*([^;]+);/.exec(face)[1]}`))
    .map((face) =>
      face.replace(/src:[^;]*;/, (src) => {
        // woff2 only: every browser that matters supports it, and the woff twin doubles the copy
        const m = /url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\)/.exec(src);
        if (!m) throw new Error(`no woff2 source in ${w}.css`);
        copied.add(m[1]);
        return `src: url(./files/${m[1]}) format('woff2');`;
      }),
    ),
);
const fullCss = full.join('\n') + '\n';
const hash = createHash('sha256').update(fullCss).digest('hex').slice(0, 10);
const FULL_DIR = `public/assets/fonts/zen-${hash}`;
rmSync('public/assets/fonts', { recursive: true, force: true });
mkdirSync(`${FULL_DIR}/files`, { recursive: true });
for (const f of copied) copyFileSync(`${PKG}/files/${f}`, `${FULL_DIR}/files/${f}`);
writeFileSync(`${FULL_DIR}/full.css`, fullCss);
const bytes = [...copied].reduce((n, f) => n + statSync(`${FULL_DIR}/files/${f}`).size, 0);
console.log(`${FULL_DIR}/full.css: ${full.length} @font-face rules, ${copied.size} woff2 files, ${bytes} bytes`);

// Pretendard for Korean pages (design system v4: Zen Kaku Gothic New has no Hangul). Like the subset
// above: only the 300 and 400 unicode-range slices that hold a character of the Korean pages (content,
// pages and the Korean UI strings; Latin too, since Korean pages set Latin in Pretendard as well).
// Copied under a hashed /assets/fonts/pretendard-<hash>/ and linked by Base.astro on lang="ko" pages only.
const KO_PKG = 'node_modules/pretendard/dist/web/static';
const koFiles = ['src/content/ko', 'src/pages/ko'].flatMap((d) => {
  try {
    return walk(d);
  } catch {
    return [];
  }
});
let koFont = null;
if (koFiles.length) {
  const koUsed = new Set();
  for (const file of koFiles) for (const ch of readFileSync(file, 'utf8')) koUsed.add(ch.codePointAt(0));
  // Hangul in the UI strings (src/i18n/ui.ts holds every language; only its Korean is needed here)
  for (const ch of readFileSync('src/i18n/ui.ts', 'utf8')) if (/[\u1100-\u11ff\u3130-\u318f\uac00-\ud7af]/.test(ch)) koUsed.add(ch.codePointAt(0));
  const koCopied = new Set();
  const koSource = readFileSync(`${KO_PKG}/pretendard-dynamic-subset.css`, 'utf8');
  // The source starts with the copyright and the SIL OFL 1.1 text: keep it with the copied fonts
  const koLicense = koSource.slice(0, koSource.indexOf('@font-face')).replace(/\/\* \[\d+\] \*\/\s*$/, '').trim();
  const koFaces = (koSource.match(/@font-face\s*\{[^}]*\}/g) ?? [])
    .filter((face) => /font-weight:\s*(300|400);/.test(face) && hits(/unicode-range:\s*([^;]+);/.exec(face)[1], koUsed))
    .map((face) =>
      face.replace(/src:[^;]*;/, (src) => {
        const m = /url\(\.\/woff2-dynamic-subset\/([^)]+\.woff2)\)/.exec(src);
        if (!m) throw new Error('no woff2 source in pretendard-dynamic-subset.css');
        koCopied.add(m[1]);
        return `src: url(./files/${m[1]}) format('woff2');`;
      }),
    );
  const koCss = `${koLicense}\n/* Subset by scripts/font-subsets.mjs */\n${koFaces.join('\n')}\n`;
  const koHash = createHash('sha256').update(koCss).digest('hex').slice(0, 10);
  const KO_DIR = `public/assets/fonts/pretendard-${koHash}`;
  mkdirSync(`${KO_DIR}/files`, { recursive: true });
  for (const f of koCopied) copyFileSync(`${KO_PKG}/woff2-dynamic-subset/${f}`, `${KO_DIR}/files/${f}`);
  writeFileSync(`${KO_DIR}/ko.css`, koCss);
  koFont = `/assets/fonts/pretendard-${koHash}/ko.css`;
  const koBytes = [...koCopied].reduce((n, f) => n + statSync(`${KO_DIR}/files/${f}`).size, 0);
  console.log(`${KO_DIR}/ko.css: ${koFaces.length} @font-face rules, ${koCopied.size} woff2 files, ${koBytes} bytes`);
}

writeFileSync(
  'src/styles/fonts.generated.json',
  JSON.stringify({ cmsFont: `/assets/fonts/zen-${hash}/full.css`, koFont }) + '\n',
);
